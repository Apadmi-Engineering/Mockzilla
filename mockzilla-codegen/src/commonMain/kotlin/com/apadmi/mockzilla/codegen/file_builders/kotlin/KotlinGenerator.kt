package com.apadmi.mockzilla.codegen.file_builders.kotlin

import com.apadmi.mockzilla.codegen.data.EndpointSpec
import com.apadmi.mockzilla.codegen.data.ExampleResponse

fun generateKotlinSource(tags: List<String>, endpoints: Array<EndpointSpec>): String {
    val buffer = StringBuffer()
    val remainingEndpoints = endpoints.toMutableList()

    buffer.appendLine("// GENERATED CODE")
    buffer.appendLine("// Generated by Mockzilla")
    buffer.appendLine()
    buffer.appendLine("import com.apadmi.mockzilla.lib.models.EndpointConfiguration")
    buffer.appendLine("import com.apadmi.mockzilla.lib.models.MockzillaConfig")
    buffer.appendLine("import com.apadmi.mockzilla.lib.models.MockzillaHttpResponse")
    buffer.appendLine("import io.ktor.http.HttpMethod")
    buffer.appendLine("import io.ktor.http.HttpStatusCode")

    buffer.appendLine()

    buffer.appendLine("val config: MockzillaConfig = MockzillaConfig.Builder()")

    for (tag in tags) {
        buffer.appendLine("// $tag Endpoints")
        val groupedEndpoints = remainingEndpoints.filter { it.tags.contains(tag) }
        for (endpoint in groupedEndpoints) {
            buffer.appendLine(endpointFragment(endpoint))
            remainingEndpoints.remove(endpoint)
        }
    }

    if (remainingEndpoints.isNotEmpty()) {
        if (tags.isNotEmpty()) {
            buffer.appendLine("// Other Endpoints")
        }
        for (endpoint in remainingEndpoints) {
            buffer.appendLine(endpointFragment(endpoint))
        }
    }

    buffer.appendLine(".build()")

    return buffer.toString()
}

internal fun endpointFragment(e: EndpointSpec): String = """
    .addEndpoint(
        EndpointConfiguration
            .Builder("${(e.method.name.uppercase() + e.path.replace("/", " ")).toEndpointName()}")
            .setPatternMatcher {
                method == HttpMethod("${e.method.name.uppercase()}") &&
                uri.endsWith("${e.path}")
            }
            .setDefaultHandler { 
               ${responseExpression(e.successResponse)}
            }
            .setErrorHandler { 
                ${responseExpression(e.errorResponse)}
            }
            .configureDashboardOverrides {
                ${e.otherResponses.joinToString("\n") { presetFragment(it) }}
            }
    )"""

internal fun presetFragment(r: ExampleResponse): String = """
        addPreset(
            name = "${r.name.escapeForKotlinLiteral()}",
            description = null,
            response = ${responseExpression(r)}
        )"""

internal fun responseExpression(v: ExampleResponse): String {
    return """MockzillaHttpResponse(
        statusCode = HttpStatusCode.fromValue(${v.statusCode}), 
        // TODO: Replace this with your DTO
        body = ""${'"'}${v.bodyValue.escapeJsonForKotlinLiteral()}""${'"'},
        headers = mapOf()
    )"""
}

fun String.toEndpointName(): String {
    return escapeForKotlinLiteral().replace("*", " ").replace(":", " ")
}

internal fun String.escapeForKotlinLiteral(): String {
    return replace("\\", "\\\\")
        .replace("\"", "\\\"")
        .replace("\$", "\\\$")
        .replace("\n", " ")
        .replace("\r", "\\r")
}

internal fun String.escapeJsonForKotlinLiteral(): String {
    return replace("\$", "\${'\$'}").replace("\"\"\"", "\"\"\${'\"'}")
}

